package it.classes.wrapper;

public class MainWrapper {

	public static void main(String[] args) {

		Integer number = Integer.valueOf(5);
	
		System.out.println(number);

		// AUTOBOXING

		Integer numbers = 35;

		System.out.println(numbers);

		// UNBOXING

		int nb = number;

		System.out.println(nb);
	}

}
